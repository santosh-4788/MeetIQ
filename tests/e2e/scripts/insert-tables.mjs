// Inserts results/report-tables.md into documentation/LOCALHOST_TEST_REPORT.md at the <!-- TABLES --> marker
// (or replaces the previously inserted block between the BEGIN/END markers).
import { readFileSync, writeFileSync } from 'node:fs'

const reportUrl = new URL('../../../documentation/LOCALHOST_TEST_REPORT.md', import.meta.url)
const tables = readFileSync(new URL('../results/report-tables.md', import.meta.url), 'utf8').replace(/^﻿/, '').trim()
const block = `<!-- TABLES:BEGIN (generated by tests/e2e/report.mjs) -->\n${tables}\n<!-- TABLES:END -->`
let report = readFileSync(reportUrl, 'utf8')
report = /<!-- TABLES:BEGIN[\s\S]*?<!-- TABLES:END -->/.test(report)
  ? report.replace(/<!-- TABLES:BEGIN[\s\S]*?<!-- TABLES:END -->/, block)
  : report.replace('<!-- TABLES -->', block)
writeFileSync(reportUrl, report)
console.log('tables inserted')
